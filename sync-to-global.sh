#!/usr/bin/env bash
# ==============================================================================
# sync-to-global.sh - 動態掃描 Skills、更新總索引與自動掛載全域路由表 (macOS / Linux)
# ==============================================================================

set -e

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SKILLS_DIR="$SCRIPT_DIR/skills"
RULES_DIR="$SCRIPT_DIR/rules"
GLOBAL_ANTIGRAVITY_DIR="$HOME/.gemini/antigravity"

echo "=========================================================="
echo " 🚀 Antigravity 全域 Skills 動態掃描與自動掛載工具 (Bash)"
echo "=========================================================="

if [ ! -d "$SKILLS_DIR" ]; then
    echo "❌ 錯誤：找不到 skills 目錄！"
    exit 1
fi

mkdir -p "$GLOBAL_ANTIGRAVITY_DIR/skills" "$GLOBAL_ANTIGRAVITY_DIR/rules"

echo -e "\n[1/3] 正在同步 Skills 與 Rules 至全域 Antigravity 目錄..."
cp -R "$SKILLS_DIR/"* "$GLOBAL_ANTIGRAVITY_DIR/skills/"
cp -R "$RULES_DIR/"* "$GLOBAL_ANTIGRAVITY_DIR/rules/"
echo "  ✓ 同步完成！"

GLOBAL_GEMINI_FILE="$GLOBAL_ANTIGRAVITY_DIR/GEMINI.md"

ROUTER_BLOCK="<!-- <Auto-Generated-Skills-Router> -->
# 【全域強制技能調度協定 (Global Always-On Skill Router)】
在每一個對話框、每一個回合開始前，你必須先檢查以下技能路由表。只要使用者的請求或當前操作的檔案符合任一技能的 \`trigger_condition\` 或 \`file_patterns\`，你必須**自動且無條件**先讀取對應的 \`SKILL.md\` 並嚴格套用其規範與模板，無需等待使用者開口點名：

| 技能名稱 (ID) | 適用檔案 (File Patterns) | 調度等級 | 觸發條件 (Trigger Condition) | 全域路徑 |
| :--- | :--- | :--- | :--- | :--- |
| **\`interactive-action-guide\`** | \`*.html, *.jsx, *.tsx, *.vue, *.xaml, *.cs\` | \`always\` | 當使用者要求加入實戰互動導引、操作教學、新手引導、下一步引導或介面 SOP 時，自動分析工作流並注入四周背景鎖死、中間聚光燈洞口可穿透操作且監聽真實事件的互動引導引擎。 | [interactive-action-guide]($GLOBAL_ANTIGRAVITY_DIR/skills/interactive-action-guide/SKILL.md) |
| **\`skill-scaffold\`** | \`SKILL.md, *.ps1, *.sh\` | \`contextual\` | 當使用者要求新增、建立、打包或擴充一個新的 AI Agent Skill 時，必須主動調用此技能以產生符合標準規範的骨架並自動同步全域。 | [skill-scaffold]($GLOBAL_ANTIGRAVITY_DIR/skills/skill-scaffold/SKILL.md) |
| **\`ui-layout-theme-guard\`** | \`*.html, *.css, *.jsx, *.tsx, *.vue, *.xaml, *.cs\` | \`always\` | 當生成、修改或美化任何 Web 網頁 (HTML/CSS) 或 C# (WPF/WinForms) 介面代碼時，必須主動套用此規範防止跑版與刺眼配色。 | [ui-layout-theme-guard]($GLOBAL_ANTIGRAVITY_DIR/skills/ui-layout-theme-guard/SKILL.md) |
| **\`wpf-embedded-manual-and-docs\`** | \`*.xaml, *.cs, *.md\` | \`contextual\` | 當使用者要求建立、更新或同步 WPF 應用程式內嵌說明手冊、可縮放/平移向量流程圖與技術手冊章節卡片時調用。 | [wpf-embedded-manual-and-docs]($GLOBAL_ANTIGRAVITY_DIR/skills/wpf-embedded-manual-and-docs/SKILL.md) |
<!-- </Auto-Generated-Skills-Router> -->"

echo -e "\n[2/3] 正在動態更新全域 GEMINI.md 路由表..."
touch "$GLOBAL_GEMINI_FILE"
EXISTING_CONTENT="$(cat "$GLOBAL_GEMINI_FILE" || true)"

if echo "$EXISTING_CONTENT" | grep -q "<Auto-Generated-Skills-Router>"; then
    python3 -c "
import re
content = open('$GLOBAL_GEMINI_FILE').read()
router = '''$ROUTER_BLOCK'''
new_content = re.sub(r'<!-- <Auto-Generated-Skills-Router> -->.*?<!-- </Auto-Generated-Skills-Router> -->', router, content, flags=re.S)
open('$GLOBAL_GEMINI_FILE', 'w').write(new_content)
" 2>/dev/null || true
else
    echo -e "$ROUTER_BLOCK\n\n$EXISTING_CONTENT" > "$GLOBAL_GEMINI_FILE"
fi

echo "  ✓ 全域 GEMINI.md 已成功注入動態路由表！"

echo -e "\n=========================================================="
echo " 🎉 全域同步順利完成！"
echo "=========================================================="
